func TestUPolynomialFactorRegisteredThirtySevenNumericFixtures(t *testing.T) {
	primeBudget := arena.NewBudget(1 << 27)
	primes, e := primegen.NewGenerator(primeBudget)
	if e != nil {
		t.Fatal(e)
	}
	t.Cleanup(func() {
		if e := primes.Close(); e != nil {
			t.Error(e)
		}
		if primeBudget.Used() != 0 {
			t.Error(primeBudget.Used())
		}
	})
	count := 0
	for idx, f := range upolyFactorRegisteredFixtures {
		t.Run(fmt.Sprint(idx+1), func(t *testing.T) {
			m, _, _ := upolySourceOwner(t)
			service, e := NewUPolynomialFactorizationService(m, UPolynomialFactorizationConfig{Primes: primes})
			if e != nil {
				t.Fatal(e)
			}
			t.Cleanup(func() {
				if e := service.Close(); e != nil {
					t.Error(e)
				}
			})
			fs, e := m.NewFactors()
			if e != nil {
				t.Fatal(e)
			}
			t.Cleanup(func() {
				if e := fs.Close(); e != nil {
					t.Error(e)
				}
			})
			p, e := m.NewPolynomial()
			if e != nil {
				t.Fatal(e)
			}
			t.Cleanup(func() {
				if e := m.DelPolynomial(&p); e != nil {
					t.Error(e)
				}
			})
			input := make([]unumeral.Int, len(f.coeffs))
			for i, s := range f.coeffs {
				if e := m.IntegerManager().SetString(&input[i], s); e != nil {
					t.Fatal(e)
				}
			}
			if e := m.SetInts(p, input); e != nil {
				t.Fatal(e)
			}
			for i := range input {
				if e := m.IntegerManager().Del(&input[i]); e != nil {
					t.Fatal(e)
				}
			}
			// Qualification only: one explicit dense axis, canonical zero/trailing term.
			// Source is_univariate/monomial RC/normalization/conversion remain OPEN.
			if len(f.coeffs) > 0 && f.coeffs[len(f.coeffs)-1] == "0" {
				t.Fatal("dense input qualification")
			}
			v := mustUPolyView(t, m, p)
			_, e = service.Factor(v, fs, UPolynomialFactorParams{MaxPrime: f.maxPrime, PrimeTrials: f.trials, MaxSearchSize: f.search})
			if e != nil {
				t.Fatal(e)
			}
			n, e := fs.DistinctFactors()
			if e != nil || n != f.distinct {
				t.Fatal("source distinct-factor ENSURE", idx, n, e)
			}
			count++
			out, e := m.NewPolynomial()
			if e != nil {
				t.Fatal(e)
			}
			defer func() {
				if e := m.DelPolynomial(&out); e != nil {
					t.Error(e)
				}
			}()
			if e := fs.Multiply(out); e != nil {
				t.Fatal(e)
			}
			same, e := m.Equal(p, out)
			if e != nil || !same {
				t.Fatal("source reconstruction ENSURE", idx, same, e)
			}
			count++
		})
	}
	if count != 74 {
		t.Fatal("numeric source assertion count", count)
	}
	t.Log("74 direct numeric ENSURE executions;37 dense qualifications, not original multivariate predicates")
}
