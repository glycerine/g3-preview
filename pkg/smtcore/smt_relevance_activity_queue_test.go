func relevanceActivityFixture(t *testing.T) (*ast.ASTManager, *SMTInternalizerState, *SMTRelevancyPropagator, *SMTActivityCaseSplitQueue) {
	t.Helper()
	m := astTestManager(t)
	_, p, s := smtInternalizerFixture(t, m, nil)
	q, err := NewSMTActivityCaseSplitQueue(s)
	astTestMust(t, err)
	astTestMust(t, q.ConfigurePhases(SMTParamsState{CaseSplitStrategy: 4, RelevancyLvl: 2}))
	return m, s, p, q
}

// This seed's first draw exceeds the source fixed 2% random-branch threshold.
func nextRelevanceActivityWithoutRandom(t *testing.T, s *SMTInternalizerState, q *SMTActivityCaseSplitQueue) int32 {
	t.Helper()
	s.random.SetSeed(10000)
	variable, _, err := q.NextCaseSplit()
	astTestMust(t, err)
	return variable
}

func TestSMTRelevanceActivityEventAdmissionAndScopedHead(t *testing.T) {
	m, s, p, q := relevanceActivityFixture(t)
	before := smtRelevancyBool(t, m, "relact-before-search")
	base := smtRelevancyBool(t, m, "relact-base")
	for _, term := range []ast.ASTHandle{before, base} {
		astTestMust(t, s.Internalize(term, true))
	}
	astTestMust(t, p.MarkRelevant(before))
	if len(s.relevanceActivity.entries) != 0 {
		t.Fatal("internalized pre-search event must be filtered at signed -1")
	}
	astTestMust(t, s.beginSearchPersistence(0, SMTParamsState{}))
	t.Cleanup(func() { astTestMust(t, s.endSearchPersistence()) })
	astTestMust(t, p.MarkRelevant(base))
	baseVar, _ := s.BoolVar(base)
	if got := nextRelevanceActivityWithoutRandom(t, s, q); got != baseVar || s.relevanceActivity.head != 0 {
		t.Fatal("base FIFO candidate/head", got, baseVar)
	}
	astTestMust(t, s.PushScope())
	astTestMust(t, s.AssignLiteral(NewSMTLiteral(baseVar, false), NewSMTBooleanAxiom()))
	child := smtRelevancyBool(t, m, "relact-child")
	astTestMust(t, s.Internalize(child, true))
	astTestMust(t, p.MarkRelevant(child))
	childVar, _ := s.BoolVar(child)
	if len(s.relevanceActivity.entries) != 1 {
		t.Fatal("new search variable entered base relevance queue")
	}
	if got := nextRelevanceActivityWithoutRandom(t, s, q); got != childVar || s.relevanceActivity.head != 1 {
		t.Fatal("delayed selection after base exhaustion", got, childVar)
	}
	astTestMust(t, s.PopScopes(1))
	if s.relevanceActivity.head != 0 || s.relevanceActivity.delayed.Contains(childVar) {
		t.Fatal("pop lost head restoration or retained deleted delayed variable")
	}
	if got := nextRelevanceActivityWithoutRandom(t, s, q); got != baseVar {
		t.Fatal("restored base candidate lost", got, baseVar)
	}
}

func TestSMTRelevanceActivityDelayedHeapConsumesAndUnassignmentReinserts(t *testing.T) {
	m, s, _, q := relevanceActivityFixture(t)
	astTestMust(t, s.beginSearchPersistence(0, SMTParamsState{}))
	t.Cleanup(func() { astTestMust(t, s.endSearchPersistence()) })
	a := smtRelevancyBool(t, m, "relact-delayed")
	astTestMust(t, s.Internalize(a, true))
	v, _ := s.BoolVar(a)
	h := s.relevanceActivity.delayed
	if !h.Contains(v) {
		t.Fatal("created search variable missing from delayed heap")
	}
	rng := s.random
	available, err := q.hasCaseSplit()
	astTestMust(t, err)
	if !available || !h.Contains(v) || s.random != rng {
		t.Fatal("availability probe consumed native state")
	}
	if got := nextRelevanceActivityWithoutRandom(t, s, q); got != v || h.Contains(v) {
		t.Fatal("native erase_min selection not consumed", got, v)
	}
	if got := nextRelevanceActivityWithoutRandom(t, s, q); got != SMTNullBoolVar {
		t.Fatal("removed unassigned variable was regenerated by a scan", got)
	}
	// Random selection still has a chance to choose this unassigned variable;
	// Go's availability probe must account for that without changing the heap.
	available, err = q.hasCaseSplit()
	astTestMust(t, err)
	if !available || h.Contains(v) {
		t.Fatal("random-branch availability or consuming membership changed")
	}
	astTestMust(t, s.PushScope())
	astTestMust(t, s.AssignLiteral(NewSMTLiteral(v, true), NewSMTBooleanAxiom()))
	astTestMust(t, s.PopScopes(1))
	if !h.Contains(v) {
		t.Fatal("unassign callback did not reinsert delayed variable")
	}
	if got := nextRelevanceActivityWithoutRandom(t, s, q); got != v {
		t.Fatal(got, v)
	}
}

func TestSMTRelevanceActivityDisplayPrefixesAndStableQueue(t *testing.T) {
	m, s, p, q := relevanceActivityFixture(t)
	a := smtRelevancyBool(t, m, "relact-display")
	astTestMust(t, s.Internalize(a, true))
	astTestMust(t, s.beginSearchPersistence(0, SMTParamsState{}))
	t.Cleanup(func() { astTestMust(t, s.endSearchPersistence()) })
	astTestMust(t, p.MarkRelevant(a))
	id, err := m.GetASTID(a)
	astTestMust(t, err)
	want := fmt.Sprintf("case-splits:\n[HEAD]=> #%d \n", id)
	var out bytes.Buffer
	astTestMust(t, s.DisplayRelevanceActivityQueue(&out))
	if out.String() != want {
		t.Fatal(out.String(), want)
	}
	before := m.Stats()
	for cut := 0; cut < len(want); cut++ {
		w := &smtLRAOutputPrefix{remaining: cut}
		if err := s.DisplayRelevanceActivityQueue(w); !errors.Is(err, io.ErrClosedPipe) || w.text.String() != want[:cut] {
			t.Fatal(cut, err, w.text.String(), want[:cut])
		}
	}
	if err := s.DisplayRelevanceActivityQueue(smtLRAShortOutput{}); !errors.Is(err, io.ErrShortWrite) {
		t.Fatal(err)
	}
	if before != m.Stats() || s.relevanceActivity.head != 0 {
		t.Fatal("display mutated owner or head")
	}
	v, _ := s.BoolVar(a)
	astTestMust(t, s.AssignLiteral(NewSMTLiteral(v, false), NewSMTBooleanAxiom()))
	if got := nextRelevanceActivityWithoutRandom(t, s, q); got != SMTNullBoolVar {
		t.Fatal(got)
	}
	out.Reset()
	astTestMust(t, s.DisplayRelevanceActivityQueue(&out))
	if want := fmt.Sprintf("case-splits:\n#%d \n", id); out.String() != want {
		t.Fatal("end cursor or consumed entry", out.String(), want)
	}
	if err := s.DisplayRelevanceActivityQueue(nil); !errors.Is(err, ast.ErrASTHandle) {
		t.Fatal(err)
	}
}

func TestSMTRelevanceActivityHeapConstructionRefusalCanRetry(t *testing.T) {
	m := astTestManager(t)
	_, _, s := smtInternalizerFixture(t, m, nil)
	q, err := NewSMTActivityCaseSplitQueue(s)
	astTestMust(t, err)
	params := SMTParamsState{CaseSplitStrategy: 4, RelevancyLvl: 2}
	m.Budget().FailAfter(0)
	err = q.ConfigurePhases(params)
	m.Budget().FailAfter(-1)
	if err == nil || s.relevanceActivity.delayed != nil {
		t.Fatal("failed heap constructor published an owner", err)
	}
	astTestMust(t, q.ConfigurePhases(params))
	if s.relevanceActivity.delayed == nil || !s.relevanceActivity.delayed.Empty() {
		t.Fatal("retry did not construct empty source delayed heap")
	}
}
